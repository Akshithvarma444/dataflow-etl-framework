"""Regenerate prompts/claude_prompts.md verbatim from Claude Code session transcripts.

Exporting avoids retyping errors in the required prompt history. Only what the
candidate wrote is kept: tool results, assistant turns, and system reminders that
the client injects are left out.

Usage:
    python scripts/export_prompt_history.py --transcripts <dir holding *.jsonl>
"""

import argparse
import json
import re
from pathlib import Path

OUTPUT_FILE = Path(__file__).resolve().parents[1] / "prompts" / "claude_prompts.md"
SYSTEM_REMINDER = re.compile(r"<system-reminder>.*?</system-reminder>", re.DOTALL)
PASTE_TAG = re.compile(r"</?pasted_content\b[^>]*>")


def _prompt_from_entry(entry: dict) -> str | None:
    """Return the candidate's words from a transcript entry, or None if it has none."""
    if entry.get("type") != "user" or entry.get("isSidechain") or entry.get("isMeta"):
        return None
    if entry.get("isCompactSummary"):
        return None

    result = entry.get("toolUseResult")
    if isinstance(result, dict) and "answers" in result:
        answers = "\n".join(f"- {q}: {a}" for q, a in result["answers"].items())
        return f"(Answers to Claude's question)\n{answers}"

    content = entry["message"]["content"]
    blocks = [{"type": "text", "text": content}] if isinstance(content, str) else content

    parts: list[str] = []
    for block in blocks:
        if block.get("type") == "document":
            parts.append(f"[Attached document: {block.get('title', 'untitled')}]")
        elif block.get("type") == "text":
            text = PASTE_TAG.sub("", SYSTEM_REMINDER.sub("", block["text"])).strip()
            if text:
                parts.append(text)
    return "\n\n".join(parts) or None


def export(transcript_dir: Path, output: Path = OUTPUT_FILE) -> int:
    """Write the history and return how many prompts it contains."""
    prompts: list[tuple[str, str]] = []
    for path in transcript_dir.glob("*.jsonl"):
        with path.open(encoding="utf-8") as lines:
            for line in lines:
                entry = json.loads(line)
                prompt = _prompt_from_entry(entry)
                if prompt:
                    prompts.append((entry["timestamp"], prompt))
    prompts.sort(key=lambda item: item[0])

    sections = [
        "# Prompt history\n\n"
        "Every prompt given to Claude Code for this project, verbatim and in order, "
        "with ISO-8601 UTC timestamps. Generated by `scripts/export_prompt_history.py`."
    ]
    sections += [
        f"## Prompt {number} ({timestamp})\n\n{text}"
        for number, (timestamp, text) in enumerate(prompts, start=1)
    ]
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text("\n\n---\n\n".join(sections) + "\n", encoding="utf-8")
    return len(prompts)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--transcripts", type=Path, required=True)
    args = parser.parse_args()
    print(f"Exported {export(args.transcripts)} prompts to {OUTPUT_FILE}")
