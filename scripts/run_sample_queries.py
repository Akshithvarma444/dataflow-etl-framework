"""Run docs/sample_queries.sql and write the results to reports/sample_queries.md.

Usage:
    python scripts/run_sample_queries.py
"""

import re
import sys
from pathlib import Path

import pandas as pd
from sqlalchemy import text

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from src.core.config import load_settings  # noqa: E402
from src.database.connection import create_db_engine  # noqa: E402


def main() -> None:
    queries = re.split(r"^-- name: ", (ROOT / "docs" / "sample_queries.sql").read_text(encoding="utf-8"), flags=re.M)[1:]
    engine = create_db_engine(load_settings().database)
    sections = ["# Sample query results\n\nGenerated by `scripts/run_sample_queries.py` from `docs/sample_queries.sql`."]
    with engine.connect() as conn:
        for block in queries:
            title, _, sql = block.partition("\n")
            frame = pd.read_sql(text(sql), conn)
            header = "| " + " | ".join(frame.columns) + " |"
            divider = "|" + " --- |" * len(frame.columns)
            rows = ["| " + " | ".join(str(value) for value in row) + " |" for row in frame.itertuples(index=False)]
            sections.append(f"## {title.strip()}\n\n```sql\n{sql.strip()}\n```\n\n" + "\n".join([header, divider, *rows]))
    engine.dispose()
    output = ROOT / "reports" / "sample_queries.md"
    output.write_text("\n\n".join(sections) + "\n", encoding="utf-8")
    print(f"Wrote {output}")


if __name__ == "__main__":
    main()
