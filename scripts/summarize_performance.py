"""Turn the measured benchmark JSON into reports/performance_summary.md, so no figure is retyped.

Usage:
    python scripts/summarize_performance.py
"""

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
REPORTS = ROOT / "reports"
HEADER = ("| Scenario | Size | Records | Total s (median) | Range s | Extract | Validate | Transform | Load "
          "| Records/s | Peak MB |\n|---|---|---|---|---|---|---|---|---|---|---|")


def row(result: dict) -> str:
    return (f"| {result['scenario']} | {result['requested_size']:,} | {result['records']:,} | {result['total_seconds_median']:.2f} "
            f"| {result['total_seconds_min']:.2f}-{result['total_seconds_max']:.2f} | {result['extraction_seconds_median']:.2f} "
            f"| {result['validation_seconds_median']:.2f} | {result['transformation_seconds_median']:.2f} "
            f"| {result['loading_seconds_median']:.2f} | {result['records_per_second_median']:,.0f} | {result['peak_rss_mb_median']:.0f} |")


def dataset_section(path: Path) -> str:
    data = json.loads(path.read_text(encoding="utf-8"))
    results = data["results"]
    by_name = {r["scenario"]: r for r in results}
    lines = [f"## {data['dataset']}", "", HEADER, *map(row, results), ""]
    copy, many = by_name.get("staging_copy"), by_name.get("staging_executemany")
    if copy and many:
        lines.append(f"**COPY against row-at-a-time staging, {copy['requested_size']:,} requested, medians:** load stage "
                     f"{copy['loading_seconds_median']:.2f}s against {many['loading_seconds_median']:.2f}s, "
                     f"{many['loading_seconds_median'] / copy['loading_seconds_median']:.1f}x faster.")
        lines.append("")
    lines += ["**Serialization, column null mask against pd.isna per value:**", "",
              "| Table | Rows | Columns | Per value s | Column mask s | Speedup |", "|---|---|---|---|---|---|"]
    lines += [f"| {c['table']} | {c['rows']:,} | {c['columns']} | {c['per_value_seconds_median']:.3f} | "
              f"{c['column_mask_seconds_median']:.3f} | {c['speedup']:.2f}x |" for c in data["serialization_comparison"]]
    return "\n".join(lines)


def main() -> None:
    intro = ("# Performance summary\n\nGenerated by `scripts/summarize_performance.py` from `reports/performance_*.json`. "
             "Synthetic data, in a separate database, on one Windows laptop also running other containers. "
             "Each scenario is the median of 3 trials; serialization is the median of 5. Size means bookings for hotel, "
             "and orders for Olist, whose related tables make each order about 7.6 records. Use these for comparison, "
             "not as absolute capacity figures.")
    sections = [dataset_section(path) for path in sorted(REPORTS.glob("performance_*.json"))]
    output = REPORTS / "performance_summary.md"
    output.write_text("\n\n".join([intro, *sections]) + "\n", encoding="utf-8")
    print(f"Wrote {output}")


if __name__ == "__main__":
    main()
